#!/usr/bin/env python3
"""Generate tokens.css and tailwind.tokens.js from tokens.json. Standard library only.

    python3 build_tokens.py            # run from replica/design/
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
t = json.load(open(os.path.join(HERE, "tokens.json")))

css = [":root {"]
for k, v in t["color"].items():
    css.append("  --color-%s: %s;" % (k, v))
for k, v in t["font"].items():
    css.append("  --font-%s: %s;" % (k, v))
for k, v in t["type"].items():
    css.append("  --text-%s: %dpx/%dpx;  --text-%s-weight: %d;" % (k, v["size"], v["line"], k, v["weight"]))
for i, v in enumerate(t["space"]):
    css.append("  --space-%d: %dpx;" % (i, v))
for k, v in t["radius"].items():
    css.append("  --radius-%s: %dpx;" % (k, v))
for k, v in t["shadow"].items():
    css.append("  --shadow-%s: %s;" % (k, v))
for k, v in t["border-width"].items():
    css.append("  --border-%s: %dpx;" % (k, v))
for k, v in t["motion"].items():
    css.append("  --motion-%s: %s;" % (k, v))
for k, v in t["layout"].items():
    css.append("  --layout-%s: %dpx;" % (k, v))
css.append("}")
css.append("@media (prefers-reduced-motion: reduce) {")
css.append("  :root { --motion-fast: 0ms; --motion-base: 0ms; --motion-place: 0ms; --motion-shake: 0ms; --motion-stagger: 0ms; }")
css.append("}")
open(os.path.join(HERE, "tokens.css"), "w").write("\n".join(css) + "\n")

theme = {
    "colors": {k: "var(--color-%s, %s)" % (k, v) for k, v in t["color"].items()},
    "fontFamily": {k: [f.strip() for f in v.split(",")] for k, v in t["font"].items()},
    "fontSize": {k: ["%dpx" % v["size"], {"lineHeight": "%dpx" % v["line"], "fontWeight": str(v["weight"])}]
                 for k, v in t["type"].items()},
    "spacing": {str(i): "%dpx" % v for i, v in enumerate(t["space"])},
    "borderRadius": {k: "%dpx" % v for k, v in t["radius"].items()},
    "boxShadow": t["shadow"],
    "borderWidth": {k: "%dpx" % v for k, v in t["border-width"].items()},
    "transitionDuration": {k: v for k, v in t["motion"].items() if k != "ease"},
    "transitionTimingFunction": {"ease": t["motion"]["ease"]},
}
js = ("// Generated by build_tokens.py from tokens.json. Do not edit by hand.\n"
      "// Use in tailwind.config.js (NativeWind): theme: { extend: require('./tailwind.tokens') }\n"
      "module.exports = " + json.dumps(theme, indent=2) + ";\n")
open(os.path.join(HERE, "tailwind.tokens.js"), "w").write(js)
print("wrote tokens.css, tailwind.tokens.js")
