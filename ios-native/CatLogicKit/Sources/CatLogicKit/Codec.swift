import Foundation

// Compact form shared with assets/levels.json and engine/codec.ts:
// "6|001112...|135024|2" (size | region digit per cell | column per row | difficulty)
public enum Codec {
    public static func encode(_ p: SolvedPuzzle) -> String {
        "\(p.size)|\(p.regions.map(String.init).joined())|\(p.solution.map(String.init).joined())|\(p.difficulty.rawValue)"
    }

    public static func decode(_ s: String) -> SolvedPuzzle? {
        let parts = s.split(separator: "|", omittingEmptySubsequences: false)
        guard parts.count == 4, let size = Int(parts[0]), let d = Int(parts[3]), let difficulty = Difficulty(rawValue: d) else { return nil }
        let regions = parts[1].compactMap { $0.wholeNumberValue }
        let solution = parts[2].compactMap { $0.wholeNumberValue }
        guard regions.count == size * size, solution.count == size else { return nil }
        return SolvedPuzzle(puzzle: Puzzle(size: size, regions: regions), solution: solution, difficulty: difficulty)
    }
}

public enum LevelPack {
    // The 300 shipped levels (generated by scripts/gen-levels.ts)
    public static let all: [SolvedPuzzle] = {
        guard let url = Bundle.module.url(forResource: "levels", withExtension: "json"),
              let data = try? Data(contentsOf: url),
              let strings = try? JSONDecoder().decode([String].self, from: data) else { return [] }
        return strings.compactMap(Codec.decode)
    }()

    public static var count: Int { all.count }

    public static func level(_ n: Int) -> SolvedPuzzle? {
        n >= 1 && n <= all.count ? all[n - 1] : nil
    }
}
